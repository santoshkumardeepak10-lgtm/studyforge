/* =========================================
   CREATE TOPIC CARDS
========================================= */

const topicGrid = document.getElementById("topicGrid");

physicsTopics.forEach((topic, index) => {

    const card = document.createElement("div");

    card.className = "subject-card";

    card.style.cursor = "pointer";

    card.innerHTML = `
        <div class="card-icon">📚</div>

        <small>
            ${topic.cls}
        </small>

        <h3>
            ${topic.title}
        </h3>

        <p>
            ${topic.description}
        </p>

        <span>
            Open Topic →
        </span>
    `;

    card.onclick = () => openTopic(index);

    topicGrid.appendChild(card);

});


/* =========================================
   OPEN TOPIC
========================================= */

function openTopic(index) {

    const topic = physicsTopics[index];

    document.getElementById("topicClass").textContent =
        topic.cls;

    document.getElementById("topicTitle").textContent =
        topic.title;

    document.getElementById("topicDescription").textContent =
        topic.description;

    document.getElementById("topicDefinition").innerText =
        topic.definition;

    document.getElementById("topicFormula").innerText =
        topic.formula;

    document.getElementById("topicExample").innerText =
        topic.example;

    document.getElementById("topicQuestions").innerText =
        topic.questions;

    document.getElementById("topicDetails").style.display =
        "block";

    document.getElementById("topicDetails").scrollIntoView({
        behavior: "smooth"
    });

}


/* =========================================
   CLOSE TOPIC
========================================= */

function closeTopic() {

    document.getElementById("topicDetails").style.display =
        "none";

    document.getElementById("topicGrid").scrollIntoView({
        behavior: "smooth"
    });

}


/* =========================================
   MOBILE MENU
========================================= */

function toggleMenu() {

    const menu = document.getElementById("navMenu");

    menu.classList.toggle("active");

}


/* =========================================
   DARK MODE
========================================= */

function toggleTheme() {

    document.body.classList.toggle("dark");

    const isDark =
        document.body.classList.contains("dark");

    localStorage.setItem(
        "studyforge-theme",
        isDark ? "dark" : "light"
    );

}


/* =========================================
   LOAD THEME
========================================= */

function loadTheme() {

    const theme =
        localStorage.getItem("studyforge-theme");

    if (theme === "dark") {

        document.body.classList.add("dark");

    }

}


/* Load saved theme */

loadTheme();